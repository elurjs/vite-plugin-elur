/**
 * Patrón compartido de los writers tipados: primera escritura síncrona al
 * montar; las siguientes pasan por la cola DOM (dedup last-write-wins).
 */
function queueWriter(write: (value: unknown) => void): (value: unknown) => void {
  let first = true;
  let queued = false;
  let pending: unknown;
  return (value: unknown): void => {
    pending = value;
    if (first) {
      first = false;
      write(pending);
    } else if (!queued) {
      queued = true;
      _queueDOMWrite(() => {
        queued = false;
        write(pending);
      });
    }
  };
}

