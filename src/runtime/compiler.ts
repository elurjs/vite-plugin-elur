            // objeto nuevo antes de tocar la ventana media.
            for (let m = 0; m < pi; m++) remountIfReplaced(newOrder[m], m, items);
            for (let m = nk + 1; m < newLen; m++) remountIfReplaced(newOrder[m], m, items);
