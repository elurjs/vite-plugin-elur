// C.14: escritura de attr namespace-aware. En elementos SVG/MathML:
// - `className` es SVGAnimatedString (readonly) → setAttribute.
// - `xlink:href`, `xml:space`, … → setAttributeNS con su URI.
// El branch usa `namespaceURI` del target — sin cambio de firma/ABI.
const XHTML_NS = "http://www.w3.org/1999/xhtml";
const ATTR_PREFIX_NS: Record<string, string> = {
  xlink: "http://www.w3.org/1999/xlink",
  xml: "http://www.w3.org/XML/1998/namespace",
  xmlns: "http://www.w3.org/2000/xmlns/",
};

function writeAttrValue(target: Element, attrName: string, text: string, isUrl: boolean): void {
  const v = isUrl ? sanitizeUrl(text) : text;
  const isHtml = target.namespaceURI === XHTML_NS || target.namespaceURI == null;
  if (attrName === "class" && isHtml) {
    (target as HTMLElement).className = v;
    return;
  }
  const colon = attrName.indexOf(":");
  if (colon > 0 && !isHtml) {
    const ns = ATTR_PREFIX_NS[attrName.slice(0, colon)];
    if (ns) {
      target.setAttributeNS(ns, attrName, v);
      return;
    }
  }
  target.setAttribute(attrName, v);
}

function removeAttrValue(target: Element, attrName: string): void {
  const colon = attrName.indexOf(":");
  if (colon > 0 && target.namespaceURI !== XHTML_NS && target.namespaceURI != null) {
    const ns = ATTR_PREFIX_NS[attrName.slice(0, colon)];
    if (ns) {
      target.removeAttributeNS(ns, attrName.slice(colon + 1));
      return;
    }
  }
  target.removeAttribute(attrName);
}

export function __elurEvent(
  element: Node,
  eventName: string,
  modifiers: readonly string[],
  handler: unknown,
): void {
  if (typeof handler !== "function") return;
  (element as any)[`__elur_${eventName}`] = handler;
  if (modifiers.length > 0) (element as any)[`__elur_${eventName}_mods`] = modifiers;
}

export function __elurClearEvent(element: Node, eventName: string): void {
  (element as any)[`__elur_${eventName}`] = null;
  (element as any)[`__elur_${eventName}_mods`] = null;
}

export function __elurAttr(
  element: Node,
  attrName: string,
  value: unknown,
  isUrl: boolean,
  executable: boolean,
): (() => void) | null {
  const target = element as Element;
  if (executable) {
    console.warn(
      `[elur] Dynamic binding on executable attribute "${attrName}". Use @event for handlers; avoid binding untrusted values here.`,
    );
  }

  const isDomProp = (
    attrName === "value" || attrName === "checked" || attrName === "selected"
  ) && attrName in target;

  const write = (next: unknown): void => {
    if (isDomProp) {
      (target as any)[attrName] = next ?? "";
    } else if (next == null || next === false) {
      removeAttrValue(target, attrName);
    } else {
      writeAttrValue(target, attrName, String(next), isUrl);
    }
  };

  // Un Signal que llega por el path genérico (clasificación imperfecta o
  // binding compuesto) se suscribe igual que en el path T1 — no stringificar
  // el objeto.
  if (isSignalLike(value)) {
    if (_bindSignalImpl) return _bindSignalImpl(value, write);
    write(value.value);
    return null;
  }

  if (typeof value !== "function") {
    write(value);
    return null;
  }

  let first = true;
  let queued = false;
  let pending: unknown;
  return effect(() => {
    pending = (value as () => unknown)();
    if (first) {
      first = false;
      write(pending);
    } else if (!queued) {
      queued = true;
      _queueDOMWrite(() => {
        queued = false;
        write(pending);
      });
    }
  });
}

export function __elurNode(
  target: Node,
  value: unknown,
  targetIsAnchor: boolean,
  postMountHooks: Array<() => void> | null,
): { dispose: (() => void) | null; hooks: Array<() => void> } | null {
  if (typeof value === "string" || typeof value === "number") {
    const text = String(value);
    if (targetIsAnchor) target.parentNode!.replaceChild(document.createTextNode(text), target);
    else target.textContent = text;
    return null;
  }
  if (value == null || value === false) {
    if (targetIsAnchor) target.parentNode?.removeChild(target);
    return null;
  }

  const anchor = document.createTextNode("");
  if (targetIsAnchor) {
    target.parentNode!.replaceChild(anchor, target);
  } else {
    target.appendChild(anchor);
  }

  const disposes: Array<() => void> = [];
  const hooks = postMountHooks ?? [];
  _activateNodeBinding(anchor, value, disposes, hooks);
  const dispose = disposes.length === 0 ? null : () => {
    for (let i = disposes.length - 1; i >= 0; i--) disposes[i]();
  };
  return { dispose, hooks: postMountHooks ? [] : hooks };
}

