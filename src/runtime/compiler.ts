export interface ElurDerivedBinding {
  /** Dep única (pack 1-dep — sin array). */
  dep?: unknown;
  /** Deps múltiples (pack N-dep). */
  deps?: unknown[];
  get: () => unknown;
  [key: symbol]: unknown;
}

// Marca del pack T2 — Symbol.for para que el core lo detecte aunque los
// módulos sean copias distintas (plugin runtime vs hydrate/SSR del core).
export const ELUR_DERIVED = Symbol.for("elur.derived");

/**
 * Pack emitido por el plugin como arg de un binding T2:
 * `__elurDerive(dep1, dep2, () => expr)` — último arg = getter original.
 * Las deps se evalúan en la posición del arg (scope de la instancia).
 */
export function __elurDerive(...args: unknown[]): ElurDerivedBinding {
  const get = args[args.length - 1] as () => unknown;
  return { [ELUR_DERIVED]: true, deps: args.slice(0, -1), get };
}

/**
 * Variante 1-dep: `__elurDerive1(dep, () => expr)` — el caso común
 * (`class=${cond(sig)}`). Sin rest array ni slice: 1 sola allocación.
 */
export function __elurDerive1(dep: unknown, get: () => unknown): ElurDerivedBinding {
  return { [ELUR_DERIVED]: true, dep, get };
}

/**
 * Núcleo T2: una edge permanente por dep señal → re-evalúa `get` y escribe
 * sólo si el resultado cambió (compare compartido — N deps, 1 write).
 * El primer `_bindSignal` escribe el valor inicial; los siguientes evalúan
 * y comparan (no-op si igual).
 *
 * Fallback: si `_bindSignal` no existe (core ≤3.5.x) o ninguna dep es
 * Signal en runtime, cae a effect+getter — las deps del getter se trackean
 * dinámicamente, semántica idéntica al path genérico.
 */
const UNSET_DERIVED = Symbol("elur-derived-unset");

// El getter T2 lee `dep.value` — si corre tracked, suscribe al consumidor
// activo (el efecto que crea la fila) a cada dep: al primer write ese efecto
// re-evalúa y dispone los bindings. Las deps ya vienen preconectadas por
// `_bindSignal`, así que la evaluación es siempre untracked.
const _untrackImpl = (_coreSignals as Record<string, unknown>).untrack as
  | (<T>(fn: () => T) => T)
  | undefined;

// `_bindDerived(dep, get, write)` — primitivo T2 del core (≥3.6): un solo
// binding con compare+untrack internos — sin el closure `run` ni arrays.
const _bindDerivedImpl = (_coreSignals as Record<string, unknown>)._bindDerived as
  | ((dep: unknown, get: () => unknown, write: (v: unknown) => void) => () => void)
  | undefined;

function bindDerived(
  packed: ElurDerivedBinding,
  write: (v: unknown) => void,
): () => void {
  const { get } = packed;
  // Fast-path 1-dep (`dep` presente, `deps` ausente): evita el array de
  // disposers y el closure `run` cuando el core expone `_bindDerived`.
  const singleDep = packed.deps === undefined;
  if (singleDep) {
    const dep = packed.dep;
    if (_bindDerivedImpl && isSignalLike(dep)) {
      return _bindDerivedImpl(dep, get, write);
    }
    if (_bindSignalImpl && isSignalLike(dep)) {
      let prev: unknown = UNSET_DERIVED;
      return _bindSignalImpl(dep, () => {
        const v = _untrackImpl ? _untrackImpl(get) : get();
        if (v !== prev) {
          prev = v;
          write(v);
        }
      });
    }
    if (!isSignalLike(dep)) {
      // Dep no-signal: el getter no tiene deps reactivas → valor estático.
      write(_untrackImpl ? _untrackImpl(get) : get());
      return () => { };
    }
    return effect(() => write(get()));
  }
  const deps = packed.deps!;
  let prev: unknown = UNSET_DERIVED;
  const run = (): void => {
    const v = _untrackImpl ? _untrackImpl(get) : get();
    if (v !== prev) {
      prev = v;
      write(v);
    }
  };
  if (_bindSignalImpl) {
    const disposers: Array<() => void> = [];
    for (const dep of deps) {
      if (isSignalLike(dep)) disposers.push(_bindSignalImpl(dep, run));
    }
    if (disposers.length > 0) {
      return () => {
        for (const d of disposers) d();
      };
    }
    // Ninguna dep resultó Signal → el set de deps del getter es vacío:
    // valor estático — una evaluación basta.
    run();
    return () => { };
  }
  return effect(() => write(get()));
}

