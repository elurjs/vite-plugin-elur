// --- C.13: hidratación compilada — activación por posición, sin scan global --
// =============================================================================

/** Rango de markers localizado posicionalmente (sin scan global). */
export interface ElurHydrateRange {
  start: Comment;
  end: Comment;
  keyed?: Array<{ start: Comment; end: Comment; serializedKey: string }>;
  array?: Array<{ start: Comment; end: Comment }>;
}

// `_hydrateNodeRange(range, value, opts, keyed, array)` — export interno del
// core (≥3.6): activa un binding de nodo sobre markers ya localizados.
const _hydrateNodeRange = (_coreHydrate as Record<string, unknown>)._hydrateNodeRange as
  | ((range: { start: Comment; end: Comment }, value: unknown, options?: unknown, keyedItems?: ElurHydrateRange["keyed"], arrayItems?: ElurHydrateRange["array"]) => (() => void) | undefined)
  | undefined;

function _hydrateMismatch(msg: string): Error {
  return new Error(`[elur] Hydration mismatch: ${msg}`);
}

/**
 * Primer Element sibling en `from` (inclusive) — salta textos y comments.
 * El cursor del hydrate compilado nunca depende de índices fijos: el HTML
 * SSR puede intercalar whitespace que el árbol compactado no tiene.
 */
export function __elurNextEl(from: Node | null): Element {
  let cur = from;
  while (cur && cur.nodeType !== 1) cur = cur.nextSibling;
  if (!cur) throw _hydrateMismatch("expected element, reached end of siblings");
  return cur as Element;
}

/**
 * Localiza `<!--elur-N-->…<!--elur-end-N-->` y los markers keyed/array del
 * rango. `from` es el primer sibling candidato (inclusive); el start marker
 * debe aparecer antes que cualquier otro boundary elur (document order).
 */
export function __elurMarkers(from: Node | null, index: number): ElurHydrateRange {
  const startName = `elur-${index}`;
  const endName = `elur-end-${index}`;
  let cur = from;
  let start: Comment | null = null;
  while (cur) {
    if (cur.nodeType === 8) {
      const data = (cur as Comment).data;
      if (data === startName) { start = cur as Comment; break; }
      if (/^elur-(end-)?\d+$/.test(data)) {
        throw _hydrateMismatch(`expected ${startName}, found ${data}`);
      }
    }
    cur = cur.nextSibling;
  }
  if (!start) throw _hydrateMismatch(`missing marker ${startName}`);
  const range: ElurHydrateRange = { start, end: start };
  scanRangeContents(start, endName, range);
  return range;
}

/**
 * Variante in-element: los markers `elur-N`/`elur-end-N` están DENTRO de
 * `el` (targets "parent"/"text" — el contenido del elemento es el binding).
 */
export function __elurMarkersIn(el: Element, index: number): ElurHydrateRange {
  return __elurMarkers(el.firstChild, index);
}

/**
 * Recorre los descendientes del rango (TreeWalker acotado al padre del
 * start) hasta `endName` en depth 0 — recoge `elur-ki:`/`elur-ke` y
 * `elur-ai`/`elur-aiend` con las mismas reglas de anidado que scanMarkers.
 */
function scanRangeContents(start: Comment, endName: string, range: ElurHydrateRange): void {
  const parent = start.parentNode;
  if (!parent) throw _hydrateMismatch("marker without parent");
  const walker = document.createTreeWalker(parent, 128 /* SHOW_COMMENT */);
  let cur: Node | null;
  do { cur = walker.nextNode(); } while (cur && cur !== start);
  if (!cur) throw _hydrateMismatch("start marker not in parent subtree");

  let depth = 0;
  const keyedStack: Array<{ start: Comment; serializedKey: string; ignored: boolean }> = [];
  const arrayStack: Array<{ start: Comment; ignored: boolean }> = [];

  while ((cur = walker.nextNode())) {
    const data = (cur as Comment).data;
    if (depth === 0 && data === endName) {
      range.end = cur as Comment;
      return;
    }
    if (/^elur-\d+$/.test(data)) { depth++; continue; }
    if (/^elur-end-\d+$/.test(data)) {
      if (depth === 0) throw _hydrateMismatch(`unexpected ${data} inside ${start.data}`);
      depth--;
      continue;
    }
    if (depth !== 0) continue;
    const ki = /^elur-ki:(.+)$/.exec(data);
    if (ki) {
      keyedStack.push({ start: cur as Comment, serializedKey: ki[1], ignored: keyedStack.length > 0 });
      continue;
    }
    if (data === "elur-ke") {
      const k = keyedStack.pop();
      if (k && !k.ignored) {
        (range.keyed ??= []).push({ start: k.start, end: cur as Comment, serializedKey: k.serializedKey });
      }
      continue;
    }
    if (data === "elur-ai") {
      arrayStack.push({ start: cur as Comment, ignored: arrayStack.length > 0 });
      continue;
    }
    if (data === "elur-aiend") {
      const a = arrayStack.pop();
      if (a && !a.ignored) {
        (range.array ??= []).push({ start: a.start, end: cur as Comment });
      }
      continue;
    }
  }
  throw _hydrateMismatch(`missing end marker ${endName}`);
}

/**
 * Activa un binding de nodo sobre un rango ya localizado. Requiere el
 * export interno `_hydrateNodeRange` del core; si falta (core antiguo) lanza
 * — hydrate() captura el error y remonta, semántica preservada.
 */
export function __elurHydrateRange(
  range: ElurHydrateRange,
  value: unknown,
  options?: unknown,
): () => void {
  if (!_hydrateNodeRange) {
    throw _hydrateMismatch("compiled hydration requires core with _hydrateNodeRange");
  }
  // Repeat dual (KeyedList + protocol): el path keyed estático de
  // hydrateNodeValue reconcilia una sola vez. Envuelto en thunk cae al
  // effect de activateNode — el getter `items` trackea `readItems` y cada
  // cambio de la lista re-reconcilia dentro del effect.
  const isDualRepeat = value != null && typeof value === "object" &&
    (value as Record<string, unknown>).__isKeyedList === true &&
    (value as Record<PropertyKey, unknown>)[ELUR_RENDER_PROTOCOL] != null;
  const hydrated = isDualRepeat
    ? () => { void (value as { items: unknown }).items; return value; }
    : value;
  return _hydrateNodeRange(range, hydrated, options, range.keyed, range.array) ?? (() => { });
}

/**
 * Localiza el root element del template dentro de `root` (top-level) o
 * dentro de `bounds` (descriptor anidado en otro binding).
 */
export function __elurHydrateRoot(
  root: ParentNode,
  bounds?: { start: Comment; end: Comment } | null,
): Element {
  if (bounds) {
    const el = __elurNextEl(bounds.start.nextSibling);
    if (!(el.compareDocumentPosition(bounds.end) & 4 /* FOLLOWING */)) {
      throw _hydrateMismatch("template root element not inside its bounds");
    }
    return el;
  }
  return __elurNextEl((root as Element).firstChild ?? null);
}
