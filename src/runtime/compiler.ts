/**
 * Attr genérico por binding: replica la semántica de `activateAttribute`
 * (ref, show/hide, prop DOM, sanitize URL, warn en executable) para los
 * contextos que el codegen especializado no emite inline. El template
 * alrededor sigue compilado — sólo este binding degrada.
 */
export function __elurGenericAttr(
  element: Node,
  attrName: string,
  value: unknown,
  isUrl: boolean,
  executable: boolean,
): () => void {
  const target = element as Element;

  if (attrName === "ref") {
    const reference = value as { el: Element | null };
    reference.el = target;
    return () => { reference.el = null; };
  }

  if (isDerivedPack(value)) value = value.get;
  // Core antiguo sin `_bindSignal`: la señal se normaliza al getter
  // `() => sig.value` — mismas deps que el arrow original, semántica igual.
  if (!_bindSignalImpl && isSignalLike(value)) {
    const sig = value as Signal<unknown>;
    value = () => sig.value;
  }

  if (attrName === "show" || attrName === "hide") {
    const htmlEl = target as HTMLElement;
    let originalDisplay: string | null = null;
    const writeVisible = (v: unknown): void => {
      const shouldShow = attrName === "show" ? Boolean(v) : !Boolean(v);
      if (originalDisplay === null) originalDisplay = htmlEl.style.display || "";
      htmlEl.style.display = shouldShow ? originalDisplay : "none";
    };
    if (_bindSignalImpl && isSignalLike(value)) return _bindSignalImpl(value, writeVisible);
    if (typeof value === "function") {
      let queued = false;
      let pending = false;
      let first = true;
      return effect(() => {
        pending = Boolean((value as () => unknown)());
        if (first) {
          first = false;
          writeVisible(pending);
        } else if (!queued) {
          queued = true;
          _queueDOMWrite(() => {
            queued = false;
            writeVisible(pending);
          });
        }
      });
    }
    if (!(attrName === "show" ? Boolean(value) : !Boolean(value))) {
      htmlEl.style.display = "none";
    }
    return () => { };
  }

  if (executable) {
    console.warn(
      `[elur] Dynamic binding on executable attribute "${attrName}". Use @event for handlers; avoid binding untrusted values here.`,
    );
  }

  const isDomProp = (
    attrName === "value" || attrName === "checked" || attrName === "selected"
  ) && attrName in target;

  const write = (next: unknown): void => {
    if (isDomProp) {
      (target as any)[attrName] = next ?? "";
    } else if (next == null || next === false) {
      removeAttrValue(target, attrName);
    } else {
      writeAttrValue(target, attrName, String(next), isUrl);
    }
  };

  if (_bindSignalImpl && isSignalLike(value)) return _bindSignalImpl(value, write);
  if (typeof value === "function") {
    let first = true;
    let queued = false;
    let pending: unknown;
    return effect(() => {
      pending = (value as () => unknown)();
      if (first) {
        first = false;
        write(pending);
      } else if (!queued) {
        queued = true;
        _queueDOMWrite(() => {
          queued = false;
          write(pending);
        });
      }
    });
  }
  write(value);
  return () => { };
}

/**
 * Evento directo por binding: listener con once/capture/passive +
 * prevent/stop/self — lo que el dispatcher delegado no puede honrar.
 */
export function __elurGenericEvent(
  element: Node,
  eventName: string,
  modifiers: readonly string[],
  handler: unknown,
): () => void {
  if (typeof handler !== "function") return () => { };
  const opts: AddEventListenerOptions = {
    once: modifiers.includes("once"),
    capture: modifiers.includes("capture"),
    passive: modifiers.includes("passive"),
  };
  const wrapped = (e: Event): void => {
    if (modifiers.includes("prevent")) e.preventDefault();
    if (modifiers.includes("stop")) e.stopPropagation();
    if (modifiers.includes("self") && e.target !== e.currentTarget) return;
    (handler as EventListener)(e);
  };
  element.addEventListener(eventName, wrapped, opts);
  return () => element.removeEventListener(eventName, wrapped, opts);
}

