// `_bindSignal` es el primitivo T1 del core (edge permanente, sin getter ni
// tracking). Namespace import: en cores antiguos (npm ≤3.5.x) no existe —
// se cae a un effect() equivalente.
const _bindSignalImpl = (_coreSignals as Record<string, unknown>)._bindSignal as
  | (<T>(source: Signal<T>, write: (v: T) => void) => () => void)
  | undefined;

// Duck-type cross-runtime: `instanceof Signal` falla cuando el binding
// vive en otro mundo reactivo (estable vs next-2); `peek` es el marcador
// común de Signal/Computed/ReadonlySignal en los tres.
function isSignalLike(v: unknown): v is Signal<unknown> {
  return (
    typeof v === "object" &&
    v !== null &&
    typeof (v as { peek?: unknown }).peek === "function"
  );
}

/**
 * C.6 T1 texto: `text.data` sigue `sig` sin effect genérico.
 * El compiled code pasa la SEÑAL (no el getter) — escritura inicial al montar
 * + una por cambio real. Si el arg resulta no ser Signal (clasificación
 * estática vs runtime), cae al getter equivalente `() => sig.value` —
 * mismas deps que el arrow original (la cadena de members nunca trackea).
 */
export function __elurBindSignalText(
  text: Text,
  sig: unknown,
): () => void {
  const write = (v: unknown): void => {
    // Sin String(): el setter `data` coacciona igual (WebIDL DOMString).
    text.data = v == null || v === false ? "" : (v as string);
  };
  if (_bindSignalImpl && isSignalLike(sig)) return _bindSignalImpl(sig, write);
  const getter = () => (sig as Signal<unknown> | null)?.value;
  return effect(() => write(getter()));
}

