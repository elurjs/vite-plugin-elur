/**
 * F4: writer para attrs HTML que el compilador resuelve en build — sin
 * `namespaceURI`/`indexOf(":")`/sanitización por escritura (sólo se emite
 * para ns html + attr no-URL + no-ejecutable). Semántica idéntica al
 * genérico: prop DOM para value/checked/selected, `class`→`className`,
 * null/false → removeAttribute.
 */
export function __elurAttrWriterHtml(
  element: Node,
  attrName: string,
): (value: unknown) => void {
  const target = element as HTMLElement;
  if (attrName === "class") {
    return queueWriter((v) => {
      if (v == null || v === false) target.removeAttribute("class");
      else target.className = v as string;
    });
  }
  if (
    (attrName === "value" || attrName === "checked" || attrName === "selected") &&
    attrName in target
  ) {
    return queueWriter((v) => {
      (target as any)[attrName] = v ?? "";
    });
  }
  return queueWriter((v) => {
    if (v == null || v === false) target.removeAttribute(attrName);
    else target.setAttribute(attrName, String(v));
  });
}

export function __elurNodeWriter(
  target: Node,
  getter: () => unknown,
  targetIsAnchor: boolean,
  postMountHooks: Array<() => void>,
): { active: boolean; write: (value: unknown) => void; dispose: () => void; mounted: () => void } {
  const text = document.createTextNode("");
  if (targetIsAnchor) target.parentNode!.replaceChild(text, target);
  else target.appendChild(text);

  let mounted = false;
  let first = true;
  let queued = false;
  let pending = "";
  const fallbackDisposes: Array<() => void> = [];
  const writer = {
    active: true,
    write(value: unknown) {
      if (typeof value !== "string" && typeof value !== "number") {
        writer.active = false;
        const anchor = document.createTextNode("");
        text.parentNode!.replaceChild(anchor, text);
        const hooks = mounted ? [] : postMountHooks;
        _activateNodeBinding(anchor, getter, fallbackDisposes, hooks);
        if (mounted) {
          for (let i = 0; i < hooks.length; i++) hooks[i]();
        }
        return;
      }
      pending = String(value);
      if (first) {
        first = false;
        text.data = pending;
      } else if (!queued) {
        queued = true;
        _queueDOMWrite(() => {
          queued = false;
          text.data = pending;
        });
      }
    },
    dispose() {
      for (let i = fallbackDisposes.length - 1; i >= 0; i--) fallbackDisposes[i]();
    },
    mounted() {
      mounted = true;
    },
  };
  return writer;
}

export function __elurReactiveText(
  target: Node,
  getter: () => unknown,
  targetMode: "node" | "parent" | "text",
  postMountHooks: Array<() => void>,
): { dispose: () => void; mounted: () => void } {
  const text = targetMode === "text" ? target as Text : document.createTextNode("");
  if (targetMode === "node") target.parentNode!.replaceChild(text, target);
  else if (targetMode === "parent") target.appendChild(text);

  let mounted = false;
  let fast = true;
  let first = true;
  let queued = false;
  let pending = "";
  const fallbackDisposes: Array<() => void> = [];

  const disposeEffect = effect(() => {
    if (!fast) return;
    const value = getter();
    if (typeof value !== "string" && typeof value !== "number") {
      fast = false;
      const anchor = document.createTextNode("");
      text.parentNode!.replaceChild(anchor, text);
      const hooks = mounted ? [] : postMountHooks;
      _activateNodeBinding(anchor, getter, fallbackDisposes, hooks);
      if (mounted) {
        for (let i = 0; i < hooks.length; i++) hooks[i]();
      }
      return;
    }

    pending = String(value);
    if (first) {
      first = false;
      text.data = pending;
    } else if (!queued) {
      queued = true;
      _queueDOMWrite(() => {
        queued = false;
        text.data = pending;
      });
    }
  });

  return {
    dispose() {
      disposeEffect();
      for (let i = fallbackDisposes.length - 1; i >= 0; i--) fallbackDisposes[i]();
    },
    mounted() {
      mounted = true;
    },
  };
}

